CREATE PROCEDURE CreateStudent
    @StudentId NVARCHAR(20),
    @FirstName NVARCHAR(50),
    @MiddleName NVARCHAR(50) = NULL,
    @LastName NVARCHAR(50),
    @DateOfBirth DATE,
    @Gender NVARCHAR(10) = NULL,
    @StudentType NVARCHAR(20) = NULL,
    @HouseNo NVARCHAR(50) = NULL,
    @Barangay NVARCHAR(100) = NULL,
    @Municipality NVARCHAR(100) = NULL,
    @Province NVARCHAR(100) = NULL,
    @PostalCode NVARCHAR(20) = NULL,
    @GuardianFirstName NVARCHAR(50) = NULL,
    @GuardianMiddleName NVARCHAR(50) = NULL,
    @GuardianLastName NVARCHAR(50) = NULL,
    @GuardianContact NVARCHAR(20) = NULL,
    @GuardianRelationship NVARCHAR(50) = NULL,
    @GuardianGender NVARCHAR(10) = NULL,
    @GuardianHouseNo NVARCHAR(50) = NULL,
    @GuardianBarangay NVARCHAR(100) = NULL,
    @GuardianMunicipality NVARCHAR(100) = NULL,
    @GuardianProvince NVARCHAR(100) = NULL,
    @GuardianPostalCode NVARCHAR(20) = NULL
AS
BEGIN
    INSERT INTO Students (
        StudentId,
        FirstName,
        MiddleName,
        LastName,
        DateOfBirth,
        Gender,
        StudentType,
        HouseNo, 
        Barangay,
        Municipality,
        Province, 
        PostalCode,
        GuardianFirstName,
        GuardianMiddleName,
        GuardianLastName, 
        GuardianContact, 
        GuardianRelationship,
        GuardianGender,
        GuardianHouseNo,
        GuardianBarangay, 
        GuardianMunicipality,
        GuardianProvince,
        GuardianPostalCode, Status
    ) 
    VALUES (
        @StudentId,
        @FirstName,
        @MiddleName,
        @LastName,
        @DateOfBirth,
        @Gender, 
        @StudentType,
        @HouseNo,
        @Barangay, 
        @Municipality,
        @Province, 
        @PostalCode,
        @GuardianFirstName,
        @GuardianMiddleName,
        @GuardianLastName,
        @GuardianContact, 
        @GuardianRelationship,
        @GuardianGender,
        @GuardianHouseNo, 
        @GuardianBarangay, 
        @GuardianMunicipality, 
        @GuardianProvince, 
        @GuardianPostalCode, 'Active'
    );
END